#include "caml/m.h"

    .global caml_garbage_collection
    .literal_position


// trap_ptr	.req	f0
// alloc_ptr	.req	f1
// domain_state_ptr	.req	f2


        .set    domain_curr_field, 0
#define DOMAIN_STATE(c_type, name) \
        .equ    domain_field_caml_##name, domain_curr_field ; \
        .set    domain_curr_field, domain_curr_field + 1
#include "../runtime/caml/domain_state.tbl"
#undef DOMAIN_STATE

#define Caml_state(var) 8*domain_field_caml_##var


    .text
    .literal_position
    .globl caml_system__code_begin
caml_system__code_begin:

    .align  4
    .globl  caml_call_gc
/*
    Calls generated by emit.mlp
    Updates f1 and f2 after garbage collection.
    -> Called using CALL0 ABI.
    a2-a11 are saved.
 */
caml_call_gc:
.Lcaml_call_gc:
/* Record the OCaml frame.  caml_call_gc is entered with call0, and the
   caml_allocN helpers branch here rather than call, so sp and a0 are
   still those of the OCaml frame the allocation point describes. */
    rfr     a15, f2
    s32i    a0, a15, Caml_state(last_return_address)
    s32i    sp, a15, Caml_state(bottom_of_stack)
/* Save allocation pointer.  caml_garbage_collection derives the request
   size from it, so it has to be stored before the collector runs. */
    ssi     f1, a15, Caml_state(young_ptr)
/* Save trap pointer in case an exception is raised during GC */
    ssi     f0, a15, Caml_state(exception_pointer)
/* Reserve a 64-byte block for the register roots (13 words, rounded up
   to keep sp 16-byte aligned).  This uses movsp rather than a plain add
   because the 16 bytes below sp hold the caller's spilled base save
   area, which the block would otherwise overwrite.  movsp takes the
   window increment from the top bits of a0, so a0 is scratched here and
   reloaded from last_return_address before returning - the callback link
   in .Ljump_to_caml restores that field around any OCaml the collector
   runs, so it survives finalisers. */
    movi    a0, 2
    slli    a0, a0, 30
    addi    a15, sp, -64
    movsp   sp, a15
/* Save OCaml's registers where the frame descriptors say they are:
   record_frame_label emits (i << 1) | 1 for Proc.phys_reg i, and
   caml_do_local_roots_nat reads gc_regs[i], so slot i must hold the
   register phys_reg i denotes, i.e. a(i+2). */
    s32i    a2, sp, 0
    s32i    a3, sp, 4
    s32i    a4, sp, 8
    s32i    a5, sp, 12
    s32i    a6, sp, 16
    s32i    a7, sp, 20
    s32i    a8, sp, 24
    s32i    a9, sp, 28
    s32i    a10, sp, 32
    s32i    a11, sp, 36
    s32i    a12, sp, 40
    s32i    a13, sp, 44
    s32i    a14, sp, 48
    rfr     a15, f2
    s32i    sp, a15, Caml_state(gc_regs)
/* Call the garbage collector */
    call12  caml_garbage_collection
/* Reload the registers: the collector rewrites the roots in place when
   it promotes values out of the minor heap or compacts. */
    l32i    a2, sp, 0
    l32i    a3, sp, 4
    l32i    a4, sp, 8
    l32i    a5, sp, 12
    l32i    a6, sp, 16
    l32i    a7, sp, 20
    l32i    a8, sp, 24
    l32i    a9, sp, 28
    l32i    a10, sp, 32
    l32i    a11, sp, 36
    l32i    a12, sp, 40
    l32i    a13, sp, 44
    l32i    a14, sp, 48
/* Reload new allocation pointer and limit */
    rfr     a15, f2
    lsi     f1, a15, Caml_state(young_ptr) /* Load new f1 */
/* Drop the block, then recover the return address */
    movi    a0, 2
    slli    a0, a0, 30
    addi    a15, sp, 64
    movsp   sp, a15
    rfr     a15, f2
    l32i    a0, a15, Caml_state(last_return_address)
/* Return to caller */
    ret
    .type   caml_call_gc, %function
    .size   caml_call_gc, .-caml_call_gc

    .literal_position


    .align  4
    .globl  caml_alloc1
/*
-> Called using CALL0 ABI.
Destroys every register
 */
caml_alloc1:
.Lcaml_alloc1:
    rfr     a11, f1        /* Read alloc ptr */
    addi    a11, a11, -8          /* Perform update */
    wfr     f1, a11        /* Save alloc ptr */
    rfr     a15, f2 /* Read domain state */
    l32i    a12, a15, Caml_state(young_limit) /* Read alloc limit */
    bltu    a11, a12, caml_call_gc  /* Call gc on overflow */
    ret /* Otherwise returns. */

    .align  4
    .globl  caml_alloc2
/*
-> Called using CALL0 ABI.
Destroys every register
 */
caml_alloc2:
.Lcaml_alloc2:
    rfr     a11, f1        /* Read alloc ptr */
    addi    a11, a11, -12          /* Perform update */
    wfr     f1, a11        /* Save alloc ptr */
    rfr     a15, f2 /* Read domain state */
    l32i    a12, a15, Caml_state(young_limit) /* Read alloc limit */
    bltu    a11, a12, caml_call_gc  /* Call gc on overflow */
    ret /* Otherwise returns. */

    .align  4
    .globl  caml_alloc3
/*
-> Called using CALL0 ABI.
Destroys every register
 */
caml_alloc3:
.Lcaml_alloc3:
    rfr     a11, f1        /* Read alloc ptr */
    addi    a11, a11, -16          /* Perform update */
    wfr     f1, a11        /* Save alloc ptr */
    rfr     a15, f2 /* Read domain state */
    l32i    a12, a15, Caml_state(young_limit) /* Read alloc limit */
    bltu    a11, a12, caml_call_gc  /* Call gc on overflow */
    ret /* Otherwise returns. */

/* N bytes allocation, N is in a2
-> Called using CALL0 ABI.
Destroys every register except a2
*/
    .align  4
    .globl  caml_allocN
caml_allocN:
.Lcaml_allocN:
    rfr     a11, f1      /* Read alloc ptr */
    sub     a11, a11, a2        /* Perform update */
    wfr     f1, a11      /* Save alloc ptr */
    rfr     a15, f2 /* Read domain state */
    l32i    a12, a15, Caml_state(young_limit) /* Read alloc limit */
    bltu    a11, a12, caml_call_gc  /* Call gc on overflow */
    ret /* Otherwise returns. */


    .literal_position

/* Call a C function from OCaml
-> Called using CALL0 ABI.
a6 to a11 contains function arguments
a4 contains C function to call.
a2 and a3 should be saved.
-> C is called using CALL4 ABI.
*/
    .align  4
    .globl  caml_c_call
caml_c_call:
/* Record lowest stack address and return address */
    rfr     a15, f2
    s32i    a0, a15, Caml_state(last_return_address)
    s32i    sp, a15, Caml_state(bottom_of_stack)
/* Make the exception handler alloc ptr available to the C code */
    ssi     f1, a15, Caml_state(young_ptr)
    ssi     f0, a15, Caml_state(exception_pointer)
/* Call the C function. a0-a3 are saved. */
    callx4  a4
/* Reload alloc ptr into register */
    rfr     a15, f2
    lsi     f1, a15, Caml_state(young_ptr)
/* Return */
    ret
    .type   caml_c_call, %function
    .size   caml_c_call, .-caml_c_call

    .literal_position

/* Start the OCalm program - CALL8*/
    .align  4
    .globl  caml_start_program
caml_start_program:
    entry   sp, (4+8+4+4)*4
.literal __caml_program, caml_program
    l32r    a11, __caml_program

/* Code shared with caml_callback */
/* Address of OCaml code to call is in a11 */
/* Arguments to the OCaml code are in a2...a7 */
/* Nothing is saved. */
 /* Base windowed call is 16 bytes (4 words)
  * CALL12 support: 32 bytes (8 words)
  * Stack uses 16 bytes for bottom, last_return, gc, a0
  * + 8 bytes for trap: caml_exception_pointer, .Ltrap_handler aligned (4-word boundary)
  */
.Ljump_to_caml:
/* Setup a callback link on the stack */
    .literal __Caml_state, Caml_state
    l32r    a15, __Caml_state /* Load caml domain state pointer */
    l32i    a15, a15, 0
    wfr     f2, a15 /* Save it. */
    l32i    a8, a15, Caml_state(bottom_of_stack)
    l32i    a9, a15, Caml_state(last_return_address)
    l32i    a10, a15, Caml_state(gc_regs)
    s32i    a8, sp, 16
    s32i    a9, sp, 20
    s32i    a10, sp, 24
/* Save return address */
    s32i    a0, sp, 28
/* Setup a trap frame to catch exceptions escaping the OCaml code */
    .literal .trap_handler, trap_handler
    l32r    a9, .trap_handler
    l32i    a8, a15, Caml_state(exception_pointer)
    s32i    a8, sp, 0 /* exn ptr */
    s32i    a9, sp, 4 /* trap handler */
    wfr     f0, sp  /* Save trap pointer */
/* Reload allocation pointers */
    lsi     f1, a15, Caml_state(young_ptr)
/* Move arguments for C ABI call */
    mov     a8, a11
/* Call the OCaml code */
    callx0  a8
.Lcaml_retaddr:
/* Pop the trap frame, restoring caml_exception_pointer */
    rfr     a15, f2
    l32i    a9, sp, 0
    s32i    a9, a15, Caml_state(exception_pointer)
    addi    a15, sp, 16
/* Fake call8 for correct movsp */
    movi    a0, 2
    slli	a0, a0, 30
    movsp   sp, a15
/* Pop the callback link, restoring the global variables */
.Lreturn_result:
    rfr     a15, f2
    l32i    a9, sp, 0
    s32i    a9, a15, Caml_state(bottom_of_stack)
    l32i    a9, sp, 4
    s32i    a9, a15, Caml_state(last_return_address)
    l32i    a9, sp, 8
    s32i    a9, a15, Caml_state(gc_regs)
/* Return address */
    l32i    a0, sp, 12
/* Update allocation pointer */
    ssi     f1, a15, Caml_state(young_ptr)
    retw
    .type   .Lcaml_retaddr, %function
    .size   .Lcaml_retaddr, .-.Lcaml_retaddr
    .type   caml_start_program, %function
    .size   caml_start_program, .-caml_start_program

    .literal_position


    .align 4
    .globl trap_handler
trap_handler:
/* Save exception pointer */
    rfr     a15, f2
    ssi     f0, a15, Caml_state(exception_pointer)
/* Encode exception bucket as an exception result */
    movi    a11, 2
    or      a2, a2, a11
/* The raiser popped the 8-byte trap frame, but the callback link was
   stored 16 bytes above it (.Ljump_to_caml leaves 8 bytes of padding), so
   step over the padding.  Using movsp also drags the base save area next
   to the link, which is where the retw in .Lreturn_result expects it —
   the same thing .Lcaml_retaddr's movsp does on the normal return path. */
    movi    a11, 2
    slli    a0, a11, 30
    addi    a11, sp, 8
    movsp   sp, a11
/* Return it */
    j       .Lreturn_result
    .type   trap_handler, %function
    .size   trap_handler, .-trap_handler

    .literal_position


/* Raise an exception from OCaml */
/* CALL0 */
    .align  4
    .globl  caml_raise_exn
caml_raise_exn:
/* Test if backtrace is active */
    rfr     a15, f2
    l32i    a3, a15, Caml_state(backtrace_active)
    beqz    a3, 1f
/* Give exception bucket as argument */
    mov     a6, a2
/* Stash the backtrace */
    mov     a7, a0
    mov     a8, sp
    rfr     a9, f0
    call4   caml_stash_backtrace
1:
/* Cut stack at current trap handler */
    rfr     a15, f0
/* Pop previous trap handler */
    lsi     f0, a15, 0
/* Load trap destination in f5 (then it will be loaded in a0) */
    lsi     f5, a15, 4
/* Set new stack using movsp and a fake call8.
   The trap frame is 8 bytes (Lpushtrap in emit.mlp allocates 8 and
   Ladjust_trap_depth accounts 8 per trap), so popping it moves sp by 8,
   exactly as the inline Raise_notrace sequence does.  The movsp drags the
   16-byte base save area to just below the new sp. */
    movi    a14, 2
    slli    a0, a14, 30
    addi    a15, a15, 8
    movsp   sp, a15
    rfr     a0, f5
    ret
    .literal_position


/* Raise an exception from C */
/* Domain ptr in a2, bucket in a3. */
    .align 4
    .globl caml_raise_exception
caml_raise_exception:
    entry   sp, 16
/* Keep the domain state and the bucket in registers that survive the
   spill; a2 cannot hold either of them yet, being the syscall selector. */
    mov     a15, a2
    mov     a14, a3
    movi    a2, 0
    syscall /* System call 0: flush all register windows to the stack. */
/* The bucket now goes in a2 and stays there.  It must not be in a4-a15
   across the call4 below: that rotates the window by four, so the callee's
   a2-a13 ARE the caller's a6-a15, and a14 in particular comes back
   destroyed -- which lost the exception on every raise from C that had
   backtraces enabled.  a0-a3 are outside the callee's window. */
    mov     a2, a14
/* Store domain state pointer */
    wfr     f2, a15
/* Reload trap ptr and alloc ptr */
    lsi     f0, a15, Caml_state(exception_pointer)
    lsi     f1, a15, Caml_state(young_ptr)
/* Test if backtrace is active */
    l32i    a4, a15, Caml_state(backtrace_active)
    beqz    a4, 1f
    mov     a6, a2 /* Arg1: exception bucket */
    l32i    a7, a15, Caml_state(last_return_address)
    l32i    a8, a15, Caml_state(bottom_of_stack)
    rfr     a9, f0
    call4   caml_stash_backtrace
    rfr     a15, f2 /* Reload domain state */
1:
/* Cut the stack back to where OCaml left it when it entered caml_c_call:
   the C frames below are dead.  All windows were spilled above, so a raw
   write to sp is safe, and the base save area that OCaml's stack
   adjustments drag around sits at sp - 16 exactly as after any OCaml
   stack move, so the movsp below relocates it like any other. */
    l32i    sp, a15, Caml_state(bottom_of_stack)
/* The bucket is already in a2, which is where the handler expects it. */
/* From here on this is the tail of caml_raise_exn */
    rfr     a15, f0
    lsi     f0, a15, 0 /* Pop previous trap handler */
    lsi     f5, a15, 4 /* Load trap destination */
    movi    a14, 2 /* Fake call8 for movsp */
    slli    a0, a14, 30
    addi    a15, a15, 8 /* Pop the 8-byte trap frame */
    movsp   sp, a15
    rfr     a0, f5
    ret

    .type   caml_raise_exception, %function
    .size   caml_raise_exception, .-caml_raise_exception


/* Callback from C to OCaml */

    .align  4
    .globl  caml_callback_asm
caml_callback_asm:
    entry   sp, (4+8+4+4)*4
/* Incoming C arguments: a2 = Caml_state (reloaded from the global by
   .Ljump_to_caml, so ignored here), a3 = closure, a4 = args array. */
    mov     a11, a3     /* closure */
    l32i    a2, a4, 0   /* a2 = args[0] */
    mov     a3, a11     /* a3 = closure environment */
    l32i    a11, a11, 0 /* code pointer */
    j       .Ljump_to_caml
    .type   caml_callback_asm, %function
    .size   caml_callback_asm, .-caml_callback_asm

    .literal_position

    .align  4
    .globl  caml_callback2_asm
caml_callback2_asm:
    entry   sp, (4+8+4+4)*4
/* Incoming C arguments: a2 = Caml_state (ignored), a3 = closure,
   a4 = args array. */
    mov     a11, a3     /* closure */
    mov     a10, a4     /* args */
    l32i    a2, a10, 0  /* a2 = args[0] */
    l32i    a3, a10, 4  /* a3 = args[1] */
    mov     a4, a11     /* a4 = closure */
.literal __caml_apply2, caml_apply2
    l32r    a11, __caml_apply2
    j       .Ljump_to_caml
    .type   caml_callback2_asm, %function
    .size   caml_callback2_asm, .-caml_callback2_asm

    .literal_position

    .align  4
    .globl  caml_callback3_asm
caml_callback3_asm:
    entry   sp, (4+8+4+4)*4
/* Incoming C arguments: a2 = Caml_state (ignored), a3 = closure,
   a4 = args array. */
    mov     a11, a3     /* closure */
    mov     a10, a4     /* args */
    l32i    a2, a10, 0  /* a2 = args[0] */
    l32i    a3, a10, 4  /* a3 = args[1] */
    l32i    a4, a10, 8  /* a4 = args[2] */
    mov     a5, a11     /* a5 = closure */
.literal __caml_apply3, caml_apply3
    l32r    a11, __caml_apply3
    j       .Ljump_to_caml
    .type   caml_callback3_asm, %function
    .size   caml_callback3_asm, .-caml_callback3_asm

    .literal_position


    .align  4
    .globl  caml_ml_array_bound_error
caml_ml_array_bound_error:
/* Load address of [caml_array_bound_error] in a4, which is where
   caml_c_call expects the C function to call (see above). */
    .literal __caml_array_bound_error, caml_array_bound_error
    l32r    a4, __caml_array_bound_error
/* Call that function */
    call0   caml_c_call
    ret
    .type   caml_ml_array_bound_error, %function
    .size   caml_ml_array_bound_error, .-caml_ml_array_bound_error

    .literal_position

    .globl  caml_system__code_end
caml_system__code_end:

