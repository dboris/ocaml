    .word   .Lcaml_retaddr  /* return address into callback */
    .short  -1              /* negative frame size => use callback link */
    .short  0               /* no roots */
    .align  2
    .type   caml_system__frametable, %object
    .size   caml_system__frametable, .-caml_system__frametable

